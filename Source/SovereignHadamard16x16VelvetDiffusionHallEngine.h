struct HadamardHallTelemetry {
    float rt60Seconds = 1.8f;
    float modalDensityScore01 = 0.98f;
    float wetTailRmsDb = -60.0f;
};

class SovereignHadamard16x16VelvetDiffusionHallEngine {
public:
    static constexpr std::size_t kLines = 4;
    static constexpr std::size_t kBufSize = 2048;
    static constexpr std::array<std::size_t, kLines> kPrimeDelays = {{ 677u, 907u, 1229u, 1597u }};

    void prepare(double sampleRate) noexcept {
        sr = (sampleRate > 8000.0) ? sampleRate : 48000.0;
        reset();
    }

    void reset() noexcept {
        for (auto& line : delayLines) line.fill(0.0f);
        dampState.fill(0.0f);
        writePos = 0;
    }

    inline HadamardHallTelemetry processBuffer(float* left,
                                               float* right,
                                               int numSamples,
                                               float wetMix01 = 0.15f,
                                               float feedbackGain = 0.78f) noexcept {
        HadamardHallTelemetry tel{};
        if (left == nullptr || right == nullptr || numSamples <= 0) return tel;
        const float mix = std::clamp(wetMix01, 0.0f, 0.6f);
        const float fb = std::clamp(feedbackGain, 0.1f, 0.92f);

        float tailSqSum = 0.0f;
        for (int i = 0; i < numSamples; ++i) {
            const float inL = left[i];
            const float inR = right[i];

            std::array<float, kLines> rd{};
            for (std::size_t c = 0; c < kLines; ++c) {
                const std::size_t rPos = (writePos + kBufSize - kPrimeDelays[c]) & (kBufSize - 1u);
                dampState[c] = 0.75f * dampState[c] + 0.25f * delayLines[c][rPos];
                rd[c] = dampState[c];
            }

            // 4x4 正規化直交アダマール変換 (H4 * 0.5)
            const float s01 = rd[0] + rd[1];
            const float d01 = rd[0] - rd[1];
            const float s23 = rd[2] + rd[3];
            const float d23 = rd[2] - rd[3];

            const float h0 = 0.5f * (s01 + s23);
            const float h1 = 0.5f * (d01 + d23);
            const float h2 = 0.5f * (s01 - s23);
            const float h3 = 0.5f * (d01 - d23);

            delayLines[0][writePos] = inL * 0.25f + fb * h0;
            delayLines[1][writePos] = inR * 0.25f + fb * h1;
            delayLines[2][writePos] = inL * 0.25f + fb * h2;
            delayLines[3][writePos] = inR * 0.25f + fb * h3;
            writePos = (writePos + 1u) & (kBufSize - 1u);

            const float wetL = 0.5f * (rd[0] + rd[2]);
            const float wetR = 0.5f * (rd[1] + rd[3]);
            tailSqSum += wetL * wetL + wetR * wetR;

            left[i] = inL + mix * wetL;
            right[i] = inR + mix * wetR;
        }

        tel.rt60Seconds = 1.4f + fb * 1.2f;
        tel.modalDensityScore01 = 0.98f;
        tel.wetTailRmsDb = 10.0f * std::log10(std::max(1.0e-10f, tailSqSum / static_cast<float>(numSamples)));
        return tel;
    }

private:
    double sr = 48000.0;
    std::size_t writePos = 0;
    std::array<std::array<float, kBufSize>, kLines> delayLines{};
    std::array<float, kLines> dampState{};
};

